CREATE SCHEMA IF NOT EXISTS RAW_PRD.STRIKER_WEBSITE;

CREATE TABLE IF NOT EXISTS RAW_PRD.STRIKER_WEBSITE.WEBSITE_PROVIDER_REQUESTS (
    SUBMISSION_ID VARCHAR(36) NOT NULL,
    SUBMITTED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    PRACTICE_NAME VARCHAR(300) NOT NULL,
    PRACTICE_TYPE VARCHAR(100) NOT NULL,
    PRACTICE_PHONE VARCHAR(60) NOT NULL,
    PRACTICE_ADDRESS VARCHAR(1000),
    PRESCRIBER_NAME VARCHAR(300) NOT NULL,
    CREDENTIALS VARCHAR(100),
    NPI VARCHAR(10) NOT NULL,
    LICENSE_NUMBER VARCHAR(100),
    EMAIL VARCHAR(254) NOT NULL,
    PHONE VARCHAR(60),
    MESSAGE VARCHAR(10000) NOT NULL,
    REFERRAL_SOURCE VARCHAR(1000),
    CATEGORIES ARRAY
);

CREATE TABLE IF NOT EXISTS RAW_PRD.STRIKER_WEBSITE.WEBSITE_PATIENT_QUESTIONS (
    SUBMISSION_ID VARCHAR(36) NOT NULL,
    SUBMITTED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    NAME VARCHAR(300) NOT NULL,
    EMAIL VARCHAR(254) NOT NULL,
    PHONE VARCHAR(60),
    PROVIDER_NAME VARCHAR(300),
    MESSAGE VARCHAR(10000) NOT NULL
);

CREATE TABLE IF NOT EXISTS RAW_PRD.STRIKER_WEBSITE.WEBSITE_CAREER_APPLICATIONS (
    SUBMISSION_ID VARCHAR(36) NOT NULL,
    SUBMITTED_AT TIMESTAMP_TZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
    ROLE_TITLE VARCHAR(300) NOT NULL,
    NAME VARCHAR(300) NOT NULL,
    EMAIL VARCHAR(254) NOT NULL,
    PHONE VARCHAR(60),
    NOTE VARCHAR(10000),
    RESUME_FILENAME VARCHAR(255) NOT NULL,
    RESUME_CONTENT_TYPE VARCHAR(100) NOT NULL,
    RESUME_CONTENT BINARY NOT NULL
);

CREATE ROLE IF NOT EXISTS STRIKERRX_WEBSITE_WRITER;
GRANT USAGE ON WAREHOUSE DEVELOPER_WH TO ROLE STRIKERRX_WEBSITE_WRITER;
GRANT USAGE ON DATABASE RAW_PRD TO ROLE STRIKERRX_WEBSITE_WRITER;
GRANT USAGE ON SCHEMA RAW_PRD.STRIKER_WEBSITE TO ROLE STRIKERRX_WEBSITE_WRITER;
GRANT INSERT ON TABLE RAW_PRD.STRIKER_WEBSITE.WEBSITE_PROVIDER_REQUESTS TO ROLE STRIKERRX_WEBSITE_WRITER;
GRANT INSERT ON TABLE RAW_PRD.STRIKER_WEBSITE.WEBSITE_PATIENT_QUESTIONS TO ROLE STRIKERRX_WEBSITE_WRITER;
GRANT INSERT ON TABLE RAW_PRD.STRIKER_WEBSITE.WEBSITE_CAREER_APPLICATIONS TO ROLE STRIKERRX_WEBSITE_WRITER;
GRANT ROLE STRIKERRX_WEBSITE_WRITER TO USER "STRIKERADMIN";
